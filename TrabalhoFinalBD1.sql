CREATE DATABASE COMPANHIA_AEREA;

	USE COMPANHIA_AEREA;

	CREATE TABLE EMPRESA_AEREA (
		ID_EMPRESA INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
		NOME VARCHAR(255) NOT NULL,
		TELEFONE VARCHAR(15) NOT NULL,
		CNPJ VARCHAR(14) NOT NULL UNIQUE
		);
		
		CREATE TABLE AEROPORTO (
		ID_AEROPORTO INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
		NOME VARCHAR(255) NOT NULL,
		CIDADE VARCHAR(255) NOT NULL,
		ESTADO VARCHAR(2) NOT NULL,
		CODIGO_IATA CHAR(3) NOT NULL UNIQUE
	);
		
	CREATE TABLE AERONAVE (
		ID_AERONAVE INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
		ID_EMPRESA INT NOT NULL,
		MODELO_AERONAVE VARCHAR(255) NOT NULL,
		DATA_FABRICACAO DATE NOT NULL,
		NUMERO_POLTRONAS INT NOT NULL, 
		NUMERO_MAXIMO_TRIPULANTES INT NOT NULL,
		CAPACIDADE_MAXIMA_COMBUSTIVEL INT NOT NULL,
		CAPACIDADE_MAXIMA_VOO INT NOT NULL,
		FOREIGN KEY (ID_EMPRESA) REFERENCES EMPRESA_AEREA(ID_EMPRESA)
		);

	CREATE TABLE VOO (
		ID_VOO INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
		ID_AERONAVE INT NOT NULL,
		
		ID_AEROPORTO_ORIGEM INT NOT NULL,
		PARTIDA DATETIME NOT NULL,

		ID_AEROPORTO_DESTINO INT NOT NULL,
		CHEGADA DATETIME NOT NULL,

		FOREIGN KEY (ID_AERONAVE) REFERENCES AERONAVE(ID_AERONAVE),
		FOREIGN KEY (ID_AEROPORTO_ORIGEM) REFERENCES AEROPORTO(ID_AEROPORTO),
		FOREIGN KEY (ID_AEROPORTO_DESTINO) REFERENCES AEROPORTO(ID_AEROPORTO)
	);


	CREATE TABLE ESCALA (
		ID_ESCALA INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
		ID_AEROPORTO_ESCALA INT NOT NULL,
		CHEGADA_ESCALA DATETIME NOT NULL,
		SAIDA_ESCALA DATETIME NOT NULL,
		
		FOREIGN KEY (ID_AEROPORTO_ESCALA) REFERENCES AEROPORTO(ID_AEROPORTO)
	);

	CREATE TABLE VOO_ESCALA(
		ID_VOO INT NOT NULL,
		ID_ESCALA INT NOT NULL,
		PRIMARY KEY (ID_VOO, ID_ESCALA),
		FOREIGN KEY (ID_VOO) REFERENCES VOO(ID_VOO),
		FOREIGN KEY (ID_ESCALA) REFERENCES ESCALA(ID_ESCALA)
	);

	CREATE TABLE PASSAGEIRO (
		ID_PASSAGEIRO INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
		NOME VARCHAR(255) NOT NULL,
		DATA_NASCIMENTO DATE NOT NULL,
		SEXO VARCHAR(10) NOT NULL,
		CPF VARCHAR(11) NOT NULL UNIQUE,
		RG VARCHAR(11) NOT NULL UNIQUE,
		ESTADO_CIVIL VARCHAR(255) NOT NULL,
		NACIONALIDADE VARCHAR(255) NOT NULL,
		MALA_DE_MAO BOOLEAN DEFAULT FALSE,
		MALA_PARA_DESPACHE BOOLEAN DEFAULT FALSE,
		PREFERENCIAL BOOLEAN DEFAULT FALSE,
		EMAIL VARCHAR(255),
		TELEFONE VARCHAR(15)
	);

	CREATE TABLE POLTRONA (
    ID_VOO INT NOT NULL,
    NUMERO_POLTRONA VARCHAR(5) NOT NULL,
    TIPO_POLTRONA ENUM('JANELA', 'CORREDOR', 'MEIO') NOT NULL,
    LADO ENUM('DIREITA', 'ESQUERDA') NOT NULL,
    OCUPADA BOOLEAN DEFAULT FALSE,

    PRIMARY KEY (ID_VOO, NUMERO_POLTRONA),
    FOREIGN KEY (ID_VOO) REFERENCES VOO(ID_VOO)
);

	CREATE TABLE PASSAGEM (
    ID_PASSAGEIRO INT NOT NULL,
    ID_VOO INT NOT NULL,
    NUMERO_POLTRONA VARCHAR(5),
    CHECKIN_REALIZADO BOOLEAN DEFAULT FALSE,

    PRIMARY KEY (ID_PASSAGEIRO, ID_VOO),
    
    FOREIGN KEY (ID_PASSAGEIRO) REFERENCES PASSAGEIRO(ID_PASSAGEIRO),
    FOREIGN KEY (ID_VOO) REFERENCES VOO(ID_VOO),
    FOREIGN KEY (ID_VOO, NUMERO_POLTRONA) REFERENCES POLTRONA(ID_VOO, NUMERO_POLTRONA)
);

