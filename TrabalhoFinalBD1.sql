CREATE PROCEDURE RESERVAR_PASSAGEM(
  IN P_ID_VOO INT,
  IN P_NUMERO_POLTRONA VARCHAR(5),
  IN P_ID_PASSAGEIRO INT
)
BEGIN
  DECLARE v_ocupada BOOLEAN;

  -- Verifica se a poltrona existe e está ocupada
  SELECT OCUPADA
  INTO v_ocupada
  FROM POLTRONA
  WHERE ID_VOO = P_ID_VOO AND NUMERO_POLTRONA = P_NUMERO_POLTRONA;

  -- Se poltrona não existe, erro
  IF v_ocupada IS NULL THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Erro: Poltrona nao existe.';
  END IF;

  -- Se poltrona ocupada, erro
  IF v_ocupada THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Erro: Poltrona ja esta ocupada.';
  END IF;

  -- Insere passagem
  INSERT INTO PASSAGEM (ID_PASSAGEIRO, ID_VOO, NUMERO_POLTRONA)
  VALUES (P_ID_PASSAGEIRO, P_ID_VOO, P_NUMERO_POLTRONA);

  -- Marca poltrona como ocupada
  UPDATE POLTRONA
  SET OCUPADA = TRUE
  WHERE ID_VOO = P_ID_VOO AND NUMERO_POLTRONA = P_NUMERO_POLTRONA;
END;
//

DELIMITER ;


