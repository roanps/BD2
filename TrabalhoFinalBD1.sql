CREATE OR REPLACE VIEW VW_PASSAGEIROS_POR_VOO AS
SELECT
  p.NOME AS NOME_PASSAGEIRO,
  p.CPF,
  v.ID_VOO,
  v.PARTIDA,
  v.CHEGADA,
  pa.NUMERO_POLTRONA,
  pa.CHECKIN_REALIZADO
FROM PASSAGEM pa
JOIN PASSAGEIRO p ON pa.ID_PASSAGEIRO = p.ID_PASSAGEIRO
JOIN VOO v ON pa.ID_VOO = v.ID_VOO;

SELECT * FROM VW_PASSAGEIROS_POR_VOO;

-- qual o voo com maior numero de escalas--
SELECT 
  v.ID_VOO, 
  v.PARTIDA, 
  v.CHEGADA, 
  COUNT(ve.ID_ESCALA) AS NUMERO_ESCALAS
FROM VOO v
LEFT JOIN VOO_ESCALA ve ON v.ID_VOO = ve.ID_VOO
GROUP BY v.ID_VOO, v.PARTIDA, v.CHEGADA
ORDER BY NUMERO_ESCALAS DESC
LIMIT 1;

-- mostrar as pontronas de um voo, tanto ocupadas quanto não ocupadas--
SELECT 
    POL.NUMERO_POLTRONA,
    POL.TIPO_POLTRONA,
    POL.LADO,
    POL.OCUPADA
FROM POLTRONA POL
WHERE POL.ID_VOO = 1

-- mostrar passagens com mala despachada--
SELECT 
    P.ID_PASSAGEIRO,
    PA.NOME AS PASSAGEIRO,
    V.ID_VOO,
    POL.NUMERO_POLTRONA,
    POL.TIPO_POLTRONA,
    POL.LADO,
    PA.MALA_PARA_DESPACHE
FROM PASSAGEM P
INNER JOIN PASSAGEIRO PA ON P.ID_PASSAGEIRO = PA.ID_PASSAGEIRO
INNER JOIN VOO V ON P.ID_VOO = V.ID_VOO
INNER JOIN POLTRONA POL ON P.ID_VOO = POL.ID_VOO AND P.NUMERO_POLTRONA = POL.NUMERO_POLTRONA
WHERE PA.MALA_PARA_DESPACHE = TRUE;

SELECT 
    V.ID_VOO,
    COUNT(DISTINCT E.ID_ESCALA) AS QUANTIDADE_ESCALAS,
    COUNT(CASE WHEN PA.MALA_DE_MAO = TRUE THEN 1 END) AS QUANTIDADE_BAGAGEM_MAO
FROM VOO V
JOIN VOO_ESCALA VE ON V.ID_VOO = VE.ID_VOO
JOIN ESCALA E ON VE.ID_ESCALA = E.ID_ESCALA
JOIN PASSAGEM P ON V.ID_VOO = P.ID_VOO
JOIN PASSAGEIRO PA ON P.ID_PASSAGEIRO = PA.ID_PASSAGEIRO
GROUP BY V.ID_VOO
ORDER BY QUANTIDADE_ESCALAS DESC, QUANTIDADE_BAGAGEM_MAO DESC
LIMIT 1;

