CREATE PROCEDURE CRIAR_POLTRONAS_VOOS()
BEGIN
  DECLARE done INT DEFAULT FALSE;
  DECLARE v_id_voo INT;
  DECLARE v_num_poltronas INT;
  DECLARE v_num INT;

  DECLARE v_tipo ENUM('JANELA', 'CORREDOR', 'MEIO');
  DECLARE v_lado ENUM('DIREITA', 'ESQUERDA');

  DECLARE cur CURSOR FOR
    SELECT V.ID_VOO, A.NUMERO_POLTRONAS
    FROM VOO V
    JOIN AERONAVE A ON V.ID_AERONAVE = A.ID_AERONAVE;

  DECLARE CONTINUE HANDLER FOR NOT FOUND SET done = TRUE;

  OPEN cur;

  read_loop: LOOP
    FETCH cur INTO v_id_voo, v_num_poltronas;
    IF done THEN
      LEAVE read_loop;
    END IF;

    SET v_num = 1;

    WHILE v_num <= v_num_poltronas DO
      -- Definir tipo e lado ciclicamente
      CASE MOD(v_num - 1, 3)
        WHEN 0 THEN SET v_tipo = 'JANELA';
        WHEN 1 THEN SET v_tipo = 'CORREDOR';
        WHEN 2 THEN SET v_tipo = 'MEIO';
      END CASE;

      CASE MOD(v_num - 1, 2)
        WHEN 0 THEN SET v_lado = 'ESQUERDA';
        WHEN 1 THEN SET v_lado = 'DIREITA';
      END CASE;

      INSERT INTO POLTRONA (ID_VOO, NUMERO_POLTRONA, TIPO_POLTRONA, LADO, OCUPADA)
      VALUES (v_id_voo, CAST(v_num AS CHAR), v_tipo, v_lado, FALSE);

      SET v_num = v_num + 1;
    END WHILE;
  END LOOP;

  CLOSE cur;
END;
//

DELIMITER ;



CALL CRIAR_POLTRONAS_VOOS();


